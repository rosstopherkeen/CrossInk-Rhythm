#!/usr/bin/env python3
"""Convert a mask image into the run-length header used by the Reaction sleep screen.

Usage:
  python3 -I scripts/sleep_mask_to_header.py <mask image> src/images/SleepMaskReadResponsibly.h SLEEP_MASK_READ_RESPONSIBLY

The mask is resized to 480x800 (logical portrait) and thresholded. Light source
pixels become "inside the mask": where SleepArtGenerator applies the second set
of reaction rates, which is what makes the letterforms visible.

Stored run-length encoded, as the boot screen is. Flat bits would be 48000
bytes against a C3 app partition that is already ~98% full; the artwork is
mostly flat, so RLE costs about an eighth of that. Both consumers read the mask
one row at a time, so per-row random access is all that is needed.

Layout: ROWS[y]..ROWS[y + 1] bounds row y's runs in RUNS. Runs alternate
starting with outside-the-mask, and sum to the width. A run longer than 255 is
written 255, 0, <rest>, the zero-length run keeping the colour.
"""

import sys
from pathlib import Path

from PIL import Image

WIDTH = 480
HEIGHT = 800
THRESHOLD = 128


def encode_row(pixels, y):
    runs = []
    current = 0
    length = 0
    for x in range(WIDTH):
        bit = 1 if pixels[x, y] >= THRESHOLD else 0
        if bit == current:
            length += 1
            continue
        while length > 255:
            runs.extend((255, 0))
            length -= 255
        runs.append(length)
        current = bit
        length = 1
    while length > 255:
        runs.extend((255, 0))
        length -= 255
    runs.append(length)
    return runs


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    source, destination, symbol = sys.argv[1], sys.argv[2], sys.argv[3]

    image = Image.open(source).convert("L").resize((WIDTH, HEIGHT), Image.LANCZOS)
    pixels = image.load()

    runs = []
    offsets = []
    for y in range(HEIGHT):
        offsets.append(len(runs))
        runs.extend(encode_row(pixels, y))
    offsets.append(len(runs))
    if len(runs) > 0xFFFF:
        raise SystemExit(f"{len(runs)} runs will not fit a uint16 offset table")

    def rows(values, per_line, formatter):
        for start in range(0, len(values), per_line):
            yield "    " + " ".join(formatter(v) for v in values[start : start + per_line])

    lines = [
        "#pragma once",
        "#include <cstdint>",
        "",
        f"// Generated by scripts/sleep_mask_to_header.py from {Path(source).name}. Do not edit.",
        f"// {WIDTH}x{HEIGHT} logical portrait, run-length encoded; see that script for the layout.",
        f"inline constexpr int {symbol}_WIDTH = {WIDTH};",
        f"inline constexpr int {symbol}_HEIGHT = {HEIGHT};",
        "",
        f"// ROWS[y]..ROWS[y + 1] bounds row y's runs.",
        f"static const uint16_t {symbol}_ROWS[] = {{",
        *rows(offsets, 12, lambda v: f"{v},"),
        "};",
        "",
        f"// Alternating run lengths, starting outside the mask.",
        f"static const uint8_t {symbol}_RUNS[] = {{",
        *rows(runs, 16, lambda v: f"{v},"),
        "};",
        "",
    ]
    Path(destination).write_text("\n".join(lines))

    flat = (WIDTH + 7) // 8 * HEIGHT
    used = len(runs) + len(offsets) * 2
    print(f"{destination}: {used} bytes ({len(runs)} runs) vs {flat} flat")


if __name__ == "__main__":
    main()
